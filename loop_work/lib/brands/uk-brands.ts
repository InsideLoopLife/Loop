export function logoUrlForDomain(domain: string) {
  return `https://www.google.com/s2/favicons?domain=${encodeURIComponent(domain)}&sz=128`;
}

export function knownBrandForLabel(label: string | null | undefined) {
  const text = String(label || "");
  if (!text.trim()) return null;
  const hit = UK_BRANDS.find((entry) => entry.match.test(text));
  return hit ? { brandName: hit.brandName, domain: hit.domain, logoUrl: logoUrlForDomain(hit.domain), source: "known_brand" as const } : null;
}
